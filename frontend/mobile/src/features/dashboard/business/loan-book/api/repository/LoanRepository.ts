/**
 * Loan Book — repository contract.
 *
 * THIS INTERFACE IS THE SWAP POINT.
 *
 * Today exactly one implementation exists (MockDataRepository). Later
 * the same interface is satisfied by an API-backed implementation, and
 * later still by the platform-wide offline engine:
 *
 *      LoanRepository  (this interface)
 *              │
 *      ┌───────┼────────────────┐
 *      ▼       ▼                ▼
 *   MockData  ApiRepository   OfflineRepository
 *                              (SQLite + sync queue)
 *
 * Screens, hooks, and components never import a concrete implementation
 * — they go through loanBookApi.ts, which holds the single reference to
 * whichever repository is active. Changing data source therefore touches
 * one line, and no UI file at all.
 *
 * DESIGN CONSTRAINTS THAT MAKE THAT SWAP ACTUALLY WORK:
 *
 * 1. Every method is async, even though the mock resolves instantly.
 *    A synchronous interface would let screens accidentally depend on
 *    immediate results, and every one of those would break the day a
 *    network or SQLite call sits behind it.
 *
 * 2. Methods return domain types (Customer, LoanEntry, Payment) — never
 *    rows, envelopes, or HTTP responses. Wire-format knowledge stops at
 *    loanMapper.ts.
 *
 * 3. IDs are supplied BY THE CALLER, not generated by the repository.
 *    The client owning ID generation is what makes offline creation
 *    possible later without a server round-trip, and it is already the
 *    shape `client_generated_id` needs (Doc 04 §5.1: "a correctness
 *    requirement for offline sync, not an optimisation").
 *
 * 4. Reads return raw records, not view models. Deriving balances and
 *    statuses is the algorithms' job, so every implementation produces
 *    identical derived numbers rather than each computing its own.
 */

import type { Customer, LoanEntry, LoanHistoryEvent, Payment } from "../../types";

export interface LoanRepository {
  // --- Customers ----------------------------------------------------
  listCustomers(): Promise<Customer[]>;
  getCustomer(customerId: string): Promise<Customer | null>;
  createCustomer(customer: Customer): Promise<Customer>;
  updateCustomer(customer: Customer): Promise<Customer>;
  /** Soft-delete a customer AND cascade to their currently-open entries
   *  (entries already independently deleted keep their own record — see
   *  MockDataRepository's docstring for the exact cascade rule). */
  softDeleteCustomer(customerId: string, reason?: string): Promise<Customer>;
  /** Restores a customer, and any entries that were cascade-deleted
   *  alongside them (never an entry that was independently trashed
   *  earlier or later). */
  restoreCustomer(customerId: string): Promise<Customer>;
  /** Deleted customers still within the retention window — see
   *  algorithms/trashRetention.ts. Already-expired ones are excluded. */
  listDeletedCustomers(): Promise<Customer[]>;

  // --- Loan entries -------------------------------------------------
  listEntries(): Promise<LoanEntry[]>;
  listEntriesForCustomer(customerId: string): Promise<LoanEntry[]>;
  getEntry(entryId: string): Promise<LoanEntry | null>;
  createEntry(entry: LoanEntry): Promise<LoanEntry>;
  updateEntry(entry: LoanEntry): Promise<LoanEntry>;
  /** Soft delete (Doc 06 §17), not permanent — see
   *  algorithms/trashRetention.ts for the recovery window. */
  softDeleteEntry(entryId: string, reason?: string): Promise<LoanEntry>;
  restoreEntry(entryId: string): Promise<LoanEntry>;
  /** Deleted entries still within the retention window. */
  listDeletedEntries(): Promise<LoanEntry[]>;
  /** ALL entries for a customer, including currently-deleted ones —
   *  needed only to build a deleted customer's Trash summary. */
  listEntriesForCustomerIncludingDeleted(customerId: string): Promise<LoanEntry[]>;

  // --- Payments -----------------------------------------------------
  listPayments(): Promise<Payment[]>;
  listPaymentsForEntry(entryId: string): Promise<Payment[]>;
  createPayment(payment: Payment): Promise<Payment>;
  deletePayment(paymentId: string): Promise<void>;

  // --- History (append-only event log) -------------------------------
  appendHistoryEvent(event: LoanHistoryEvent): Promise<LoanHistoryEvent>;
  listHistory(): Promise<LoanHistoryEvent[]>;

  // --- Grace-period-inclusive reads, for TOTALS ONLY -------------------
  /**
   * Same as listEntries(), but ALSO includes entries still within the
   * 7-day Trash retention window (not yet permanently gone). Exists
   * specifically so outstanding-total calculations don't silently drop
   * real, still-recoverable debt the moment something is deleted — see
   * loanBookApi.ts's getLoanBookSummary() for the full reasoning.
   *
   * NEVER use this for a browsable list — a deleted customer/entry must
   * not be tappable or visible in ordinary navigation, only in Trash.
   * This exists purely to keep TOTALS honest.
   */
  listEntriesIncludingGracePeriod(): Promise<LoanEntry[]>;
  /** Payments belonging to grace-period entries — needed alongside
   *  listEntriesIncludingGracePeriod() so a partially-paid, recently
   *  deleted entry still shows its TRUE remaining balance in totals,
   *  not its full original amount. */
  listPaymentsIncludingGracePeriod(): Promise<Payment[]>;
}
